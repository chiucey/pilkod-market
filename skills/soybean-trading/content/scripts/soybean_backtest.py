def _score(sdu, cot, nino, drought, month):
    if sdu < 0.030:   fund = 0.92
    elif sdu < 0.045: fund = 0.80
    elif sdu < 0.060: fund = 0.65
    elif sdu < 0.075: fund = 0.52
    elif sdu < 0.090: fund = 0.38
    else:              fund = 0.20
    seasonal = {1:0.52,2:0.55,3:0.56,4:0.68,5:0.60,6:0.66,
                7:0.72,8:0.62,9:0.44,10:0.36,11:0.42,12:0.54}[month]
    if cot > 150000:   cot_sc = 0.30
    elif cot > 100000: cot_sc = 0.60
    elif cot > 60000:  cot_sc = 0.52
    else:               cot_sc = 0.45
    weather = min((max(0,drought-30)/100)*0.6 + (0.35 if nino>0.8 else(0.40 if nino<-0.8 else 0.0)), 0.90)
    return fund*0.40 + seasonal*0.20 + cot_sc*0.18 + weather*0.15

