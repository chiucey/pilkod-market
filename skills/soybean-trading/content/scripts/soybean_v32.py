def mom_score(p):
    if p > 5:  return 0.78
    elif p > 2:  return 0.68
    elif p > 0:  return 0.60
    elif p > -2: return 0.48
    elif p > -5: return 0.38
    else:        return 0.25

def seasonal(mo):
    if mo in (6, 7):   return 0.82
    elif mo in (9, 10): return 0.25
    else:                return 0.55

def weather(nino, d, mo):
    v = min(d / 100.0 * 0.6, 0.9)
    e = 0.35 if nino > 0.8 else (-0.40 if nino < -0.8 else 0.0)
    g = 0.12 if mo in (6, 7, 8) else 0.0
    return min(max(v + e + g, 0.0), 0.95)

def cot_factor(cot):
    return 0.28 if cot > 220000 else (0.40 if cot > 180000 else 0.60)

def regime(sdu, sdu_prev):
    d = sdu - (sdu_prev if sdu_prev is not None else sdu)
    if d < -0.5:   r = 0.85
    elif d < -0.2: r = 0.72
    elif d < 0.2:  r = 0.50
    elif d < 0.5:  r = 0.38
    else:           r = 0.22
    if sdu < 0.050 and d < 0: r = min(r * 1.15, 0.95)
    if sdu > 0.090 and d > 0: r = max(r * 0.70, 0.10)
    return r

# Floor (month: (min_long, min_short))
FLOOR = {
    1:(10,-15), 2:(10,-15), 3:(10,-10), 4:(25,-10), 5:(25,-10),
    6:(50,-10), 7:(50,-10), 8:(25,-25),
    9:(-30,10), 10:(-30,10), 11:(-5,-5), 12:(5,-5),
}

def signal(ym, sdu, sdu_prev, cot, nino, drought, mo, mom_pct):
    R = regime(sdu, sdu_prev)
    S = seasonal(mo)
    W = weather(nino, drought, mo)
    M = mom_score(mom_pct)
    Cc = cot_factor(cot)
    base = R*0.50 + M*0.15 + S*0.15 + W*0.10 + Cc*0.10

    if   base >= 0.75: pos = 80
    elif base >= 0.68: pos = 60
    elif base >= 0.62: pos = 45
    elif base >= 0.56: pos = 25
    elif base >= 0.48: pos = 0
    elif base >= 0.40: pos = -25
    elif base >= 0.32: pos = -45
    elif base >= 0.25: pos = -65
    else:               pos = -80

    mn, mx = FLOOR.get(mo, (0, 0))
    if pos > 0:  pos = max(pos, mn)
    elif pos < 0: pos = min(pos, mx)
    if sdu < 0.035: pos = max(pos, 85)
    if sdu < 0.050: pos = max(pos, 65)
    if sdu > 0.095: pos = min(pos, -65)
    return max(-100, min(100, pos)), base

