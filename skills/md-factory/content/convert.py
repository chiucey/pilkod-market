#!/usr/bin/env python3
"""
MD Factory - 内容结构化与Markdown生成引擎

将任意文档转换为可直接使用的结构化Markdown内容。
"""

import argparse
import os
import sys
import re
from pathlib import Path
from typing import Optional, Dict, List

try:
    from markitdown import MarkItDown
except ImportError:
    print("错误：未找到markitdown库。请先安装：")
    print("  pip install markitdown")
    sys.exit(1)

from templates import TEMPLATES, get_template, detect_template_from_content


class MDConverter:
    """
    内容结构化与Markdown生成引擎

    支持7种模板类型，自动识别内容并生成可直接使用的成品内容。
    """

    def __init__(self, verbose: bool = False):
        self.verbose = verbose
        self.md = MarkItDown()

    def convert_file(self, input_path: str) -> str:
        """将文件转换为Markdown"""
        if not os.path.exists(input_path):
            raise FileNotFoundError(f"文件不存在：{input_path}")

        if self.verbose:
            print(f"正在转换：{input_path}")

        result = self.md.convert(input_path)
        return result.text_content

    def structure_content(
        self,
        content: str,
        template: str = "auto",
        title: Optional[str] = None
    ) -> str:
        """
        将内容结构化为指定模板

        Args:
            content: 原始Markdown内容
            template: 模板类型 (auto, knowledge-card, article, tech-doc, readme, investment, action-list, comparison)
            title: 自定义标题

        Returns:
            结构化后的Markdown内容
        """
        # 自动检测模板
        if template == "auto":
            template = detect_template_from_content(content)

        tmpl = get_template(template)

        if self.verbose:
            print(f"使用模板：{tmpl.emoji} {tmpl.name}")

        # 提取标题
        if not title:
            title = self._extract_title(content) or "未命名内容"

        # 生成成品内容
        output = self._apply_template(content, tmpl, title)

        return output

    def convert_and_structure(
        self,
        input_path: str,
        template: str = "auto",
        title: Optional[str] = None
    ) -> str:
        """
        转换文件并结构化

        Args:
            input_path: 输入文件路径
            template: 模板类型
            title: 自定义标题

        Returns:
            结构化后的Markdown内容
        """
        content = self.convert_file(input_path)
        return self.structure_content(content, template, title)

    def _extract_title(self, content: str) -> Optional[str]:
        """从内容中提取标题"""
        # 尝试从H1标题提取
        h1_match = re.search(r'^#\s+(.+)$', content, re.MULTILINE)
        if h1_match:
            return h1_match.group(1).strip()

        # 尝试从第一行提取
        first_line = content.split('\n')[0].strip()
        if first_line and len(first_line) < 100:
            return first_line

        return None

    def _apply_template(self, content: str, tmpl, title: str) -> str:
        """应用模板到内容"""
        lines = content.split('\n')

        # 过滤噪音内容
        clean_lines = self._clean_content(lines)

        # 提取核心要点
        key_points = self._extract_key_points(clean_lines)

        # 生成金句
        golden_sentence = self._extract_golden_sentence(clean_lines)

        # 生成标签
        tags = self._generate_tags(content, tmpl.name)

        # 构建输出
        output = f"# {title}\n\n"

        if tmpl.name == "知识卡片":
            output += self._build_knowledge_card(title, key_points, clean_lines, golden_sentence, tags)
        elif tmpl.name == "爆款文章":
            output += self._build_article(title, clean_lines, golden_sentence, tags)
        elif tmpl.name == "技术文档":
            output += self._build_tech_doc(title, clean_lines)
        elif tmpl.name == "README生成":
            output += self._build_readme(title, key_points, clean_lines)
        elif tmpl.name == "投资分析":
            output += self._build_investment(title, clean_lines)
        elif tmpl.name == "行动清单":
            output += self._build_action_list(title, key_points)
        elif tmpl.name == "对比总结":
            output += self._build_comparison(title, clean_lines)
        else:
            output += self._build_knowledge_card(title, key_points, clean_lines, golden_sentence, tags)

        output += "\n---\n\n✨ Generated by MD Factory"
        return output

    def _clean_content(self, lines: List[str]) -> List[str]:
        """清理噪音内容"""
        clean = []
        noise_patterns = [
            r'^导航菜单',
            r'^返回顶部',
            r'^相关推荐',
            r'^广告',
            r'^copyright',
            r'^京ICP备',
            r'^\s*[$#*]{3,}$',
            r'^\s*点击展开',
        ]

        for line in lines:
            line = line.strip()
            if not line:
                continue

            # 跳过噪音行
            is_noise = False
            for pattern in noise_patterns:
                if re.search(pattern, line, re.IGNORECASE):
                    is_noise = True
                    break

            if not is_noise and len(line) > 2:
                clean.append(line)

        return clean

    def _extract_key_points(self, lines: List[str]) -> List[str]:
        """提取核心要点"""
        points = []

        # 查找列表项
        for line in lines:
            line = line.strip()
            if line.startswith(('- ', '* ', '+ ')) or re.match(r'^\d+\.', line):
                point = re.sub(r'^[\d*+\-]+[\s.]+', '', line)
                if len(point) > 5 and len(point) < 200:
                    points.append(point)

        # 如果没有列表，提取短段落
        if not points:
            for line in lines:
                if 20 < len(line) < 100 and not line.startswith('#'):
                    points.append(line)
                    if len(points) >= 5:
                        break

        return points[:5] if points else ["内容已提取"]

    def _extract_golden_sentence(self, lines: List[str]) -> str:
        """提取金句"""
        # 查找引号中的内容
        for line in lines:
            if '"' in line or '"' in line or '"' in line:
                match = re.search(r'["""].+?["""]', line)
                if match:
                    return match.group()

        # 返回较长的总结性句子
        for line in reversed(lines):
            if 30 < len(line) < 80 and not line.startswith('#'):
                return f'"{line}"'

        return '"核心内容已整理完成"'

    def _generate_tags(self, content: str, template_name: str) -> str:
        """生成标签"""
        tags = []

        # 基于关键词生成标签
        keywords = {
            "AI": ["人工智能", "AI", "机器学习", "深度学习"],
            "产品": ["产品", "功能", "特性"],
            "技术": ["代码", "开发", "API", "编程"],
            "投资": ["投资", "股票", "财务", "收益"],
            "学习": ["学习", "教程", "指南", "入门"],
            "商业": ["商业", "创业", "市场", "运营"],
        }

        for tag, words in keywords.items():
            if any(word in content for word in words):
                tags.append(f"#{tag}")

        # 添加模板相关标签
        tag_mapping = {
            "知识卡片": "#知识管理",
            "爆款文章": "#内容创作",
            "技术文档": "#技术",
            "README生成": "#开源",
            "投资分析": "#投资理财",
            "行动清单": "#效率",
            "对比总结": "#选购指南",
        }
        tags.append(tag_mapping.get(template_name, "#内容"))

        return " ".join(tags[:5])

    def _build_knowledge_card(self, title: str, points: List[str], content: List[str], golden: str, tags: str) -> str:
        """构建知识卡片"""
        # 生成TL;DR
        tldr = f"{title}的核心要点已整理完成。"

        output = "## TL;DR\n"
        output += f"{tldr}\n\n"

        output += "## 核心要点\n"
        for i, point in enumerate(points, 1):
            output += f"- {point}\n"
        output += "\n"

        output += "## 关键洞察\n"
        if len(content) > 5:
            output += f"{content[5][:200]}...\n" if len(content[5]) > 200 else f"{content[5]}\n"
        else:
            output += "详细内容请参考原文。\n"
        output += "\n"

        output += "## 金句\n"
        output += f"{golden}\n\n"

        output += "## 标签\n"
        output += f"{tags}\n"

        return output

    def _build_article(self, title: str, content: List[str], golden: str, tags: str) -> str:
        """构建爆款文章"""
        output = "## 开头钩子\n"
        output += f"你有没有想过，{title}背后隐藏着什么秘密？\n\n"

        output += "## 正文\n"
        for i, section in enumerate(content[:6], 1):
            if len(section) < 200:
                output += f"### {section[:50]}...\n\n"
            else:
                output += f"{section}\n\n"
        output += "\n"

        output += "## 结尾升华\n"
        output += f"希望通过今天的分享，大家能对{title}有更深入的理解。如果觉得有用，欢迎分享给身边的朋友！\n\n"

        output += "## 金句\n"
        output += f"{golden}\n\n"

        output += "## 标签\n"
        output += f"{tags}\n"

        return output

    def _build_tech_doc(self, title: str, content: List[str]) -> str:
        """构建技术文档"""
        output = "## 功能说明\n"
        output += f"{title}提供以下核心功能：\n\n"

        output += "## 实现原理\n"
        for line in content[:5]:
            if len(line) > 10:
                output += f"- {line}\n"
        output += "\n"

        output += "## 代码示例\n"
        output += "```python\n"
        output += f"# {title} 示例代码\n"
        output += "```\n\n"

        output += "## 注意事项\n"
        output += "- 请确保环境配置正确\n"
        output += "- 详细文档请参考官方文档\n"

        return output

    def _build_readme(self, title: str, points: List[str], content: List[str]) -> str:
        """构建README"""
        output = "## 一句话简介\n"
        output += f"{title} - 让你的工作更高效。\n\n"

        output += "## 核心功能\n"
        for point in points[:4]:
            output += f"- {point}\n"
        output += "\n"

        output += "## 快速开始\n"
        output += "### 安装\n"
        output += "```bash\npip install xxx\n```\n\n"
        output += "### 使用\n"
        output += "```python\nimport xxx\n```\n\n"

        output += "## 示例\n"
        output += "详见 examples/ 目录\n\n"

        output += "## 许可证\n"
        output += "MIT License\n"

        return output

    def _build_investment(self, title: str, content: List[str]) -> str:
        """构建投资分析"""
        output = "## 一句话结论\n"
        output += f"基于现有数据，{title}具备一定的投资价值。\n\n"

        output += "## 核心逻辑\n"
        for line in content[:4]:
            if len(line) > 10:
                output += f"- {line[:100]}\n"
        output += "\n"

        output += "## 关键数据\n"
        output += "| 指标 | 数值 |\n"
        output += "|------|------|\n"
        output += "| 数据1 | 待填充 |\n"
        output += "| 数据2 | 待填充 |\n\n"

        output += "## 风险点\n"
        output += "- 风险1：市场波动风险\n"
        output += "- 风险2：政策不确定性\n\n"

        output += "## 结论\n"
        output += "建议持续关注，谨慎决策。\n"

        return output

    def _build_action_list(self, title: str, points: List[str]) -> str:
        """构建行动清单"""
        output = "## 行动步骤\n"
        for i, point in enumerate(points[:5], 1):
            output += f"- [ ] Step {i}: {point}\n"
        output += "\n"

        output += "## 时间节点\n"
        output += "| 阶段 | 期限 | 状态 |\n"
        output += "|------|------|------|\n"
        output += "| 规划 | 第1周 | 待开始 |\n"
        output += "| 执行 | 第2-3周 | 进行中 |\n"
        output += "| 复盘 | 第4周 | 待完成 |\n\n"

        output += "## 注意事项\n"
        output += "- 确保每个步骤都有明确的目标\n"
        output += "- 定期检查进度，及时调整\n"

        return output

    def _build_comparison(self, title: str, content: List[str]) -> str:
        """构建对比总结"""
        output = "## 概览\n"
        output += f"本文对{title}进行全面对比分析。\n\n"

        output += "## 对比表格\n"
        output += "| 维度 | A方案 | B方案 |\n"
        output += "|------|-------|-------|\n"
        output += "| 价格 | 待定 | 待定 |\n"
        output += "| 功能 | 待定 | 待定 |\n"
        output += "| 适用场景 | 待定 | 待定 |\n\n"

        output += "## 结论\n"
        output += "根据实际需求选择最适合的方案。\n"

        return output


def convert_file(
    input_path: str,
    output_path: str = None,
    template: str = "auto",
    title: str = None,
    verbose: bool = False
) -> bool:
    """转换单个文件并结构化"""
    try:
        converter = MDConverter(verbose=verbose)
        result = converter.convert_and_structure(input_path, template, title)

        if output_path:
            output_dir = os.path.dirname(output_path)
            if output_dir and not os.path.exists(output_dir):
                os.makedirs(output_dir, exist_ok=True)

            with open(output_path, "w", encoding="utf-8") as f:
                f.write(result)

            if verbose:
                print(f"已保存到：{output_path}")
        else:
            print(result)

        return True

    except Exception as e:
        print(f"转换失败：{str(e)}")
        return False


def convert_directory(
    input_dir: str,
    output_dir: str = None,
    template: str = "auto",
    verbose: bool = False
) -> dict:
    """批量转换目录"""
    supported_extensions = {
        ".pdf", ".docx", ".xlsx", ".pptx",
        ".html", ".htm", ".csv", ".json", ".xml",
        ".jpg", ".jpeg", ".png", ".gif", ".bmp",
        ".mp3", ".wav", ".m4a", ".flac", ".ogg",
        ".zip", ".md", ".txt"
    }

    results = {"success": 0, "failed": 0, "skipped": 0}

    try:
        if not os.path.isdir(input_dir):
            print(f"错误：目录不存在 - {input_dir}")
            return results

        if output_dir and not os.path.exists(output_dir):
            os.makedirs(output_dir, exist_ok=True)

        converter = MDConverter(verbose=verbose)

        for root, dirs, files in os.walk(input_dir):
            for filename in files:
                file_ext = os.path.splitext(filename)[1].lower()

                if file_ext not in supported_extensions:
                    results["skipped"] += 1
                    continue

                input_path = os.path.join(root, filename)

                if output_dir:
                    rel_path = os.path.relpath(root, input_dir)
                    file_output_dir = os.path.join(output_dir, rel_path) if rel_path != "." else output_dir

                    if not os.path.exists(file_output_dir):
                        os.makedirs(file_output_dir, exist_ok=True)

                    output_name = os.path.splitext(filename)[0] + ".md"
                    output_path = os.path.join(file_output_dir, output_name)
                else:
                    output_path = None

                try:
                    if verbose:
                        print(f"正在处理：{filename}")

                    result = converter.convert_and_structure(input_path, template)

                    if output_path:
                        with open(output_path, "w", encoding="utf-8") as f:
                            f.write(result)

                    results["success"] += 1

                except Exception as e:
                    results["failed"] += 1
                    print(f"  失败：{str(e)}")

        return results

    except Exception as e:
        print(f"错误：{str(e)}")
        return results


def list_templates():
    """列出所有可用模板"""
    print("可用模板：\n")
    for key, tmpl in TEMPLATES.items():
        print(f"  {tmpl.emoji} {tmpl.name}")
        print(f"     适用：{tmpl.适用场景}")
        print()


def main():
    """主函数"""
    parser = argparse.ArgumentParser(
        description="MD Factory - 内容结构化与Markdown生成引擎",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例：
  %(prog)s document.pdf -o output.md --template knowledge-card
  %(prog)s ./docs/ -d ./output/ --template tech-doc
  %(prog)s --list-templates
        """
    )

    parser.add_argument("input", nargs="?", help="输入文件或目录路径")
    parser.add_argument("-o", "--output", help="输出文件路径")
    parser.add_argument("-d", "--directory", help="输出目录路径")
    parser.add_argument("--template", default="auto",
                        choices=["auto", "knowledge-card", "article", "tech-doc",
                                "readme", "investment", "action-list", "comparison"],
                        help="输出模板类型")
    parser.add_argument("--title", help="自定义标题")
    parser.add_argument("--verbose", action="store_true", help="显示详细输出")
    parser.add_argument("--list-templates", action="store_true", help="列出所有模板")

    args = parser.parse_args()

    if args.list_templates:
        list_templates()
        return 0

    if not args.input:
        parser.print_help()
        return 1

    if os.path.isdir(args.input):
        results = convert_directory(
            args.input,
            args.directory or args.output,
            args.template,
            args.verbose
        )
        print("\n处理完成：")
        print(f"  成功：{results['success']}")
        print(f"  失败：{results['failed']}")
        print(f"  跳过：{results['skipped']}")
        return 0 if results["failed"] == 0 else 1

    elif os.path.isfile(args.input):
        success = convert_file(
            args.input,
            args.output,
            args.template,
            args.title,
            args.verbose
        )
        return 0 if success else 1

    else:
        print(f"错误：输入路径不存在 - {args.input}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
